"""N1/N4 on the rendered book: the concept registry against the PDF build's .aux and .toc.

After a render (`render_gate.py book/`, which keeps the LaTeX files), this check reads book/index.aux and
book/index.toc and fails when
  - a registry concept's defining section (tools/reader-glossary.json, `section`) has no `\\newlabel` in the .aux,
    so a link to it would not resolve;
  - a link of the glossary appendix (Appendix H) names a section with no `\\newlabel`;
  - a concept has no line of its own in the topic index (Appendix F, generated by tools/gen_topic_index.py) that
    refers to its defining section, so it is reached only through a roll-up or not at all;
  - a concept is not reachable: its defining section is neither a target of the table of contents (.toc) nor
    the destination of its topic-index line;
  - a defining section, and so the destination of its topic-index line, is a chapter or appendix heading
    (`chapter.N` or `appendix.X` in the .aux): a roll-up, even when the registry and the index line agree.
The book has no LaTeX index (.idx); the topic index is its index.

usage: python3 tools/check_rendered_glossary.py [book_dir]      (exit 0 when clean)
"""
import json
import re
import sys
from pathlib import Path

REPORT = Path(__file__).resolve().parent.parent
_NEWLABEL = re.compile(r'^\\newlabel\{([^}]+)\}\{\{(.*)\}\{([^{}]*)\}\{\}\}\s*$')
_TOC = re.compile(r'^\\contentsline \{[a-z]+\}\{.*\}\{[^{}]*\}\{([^{}]*)\}%\s*$')
_ROLLUP = re.compile(r'^(chapter|appendix)\.[A-Z0-9]+$')
_LINK = re.compile(r'\]\(#(sec-[A-Za-z0-9_-]+)\)')


def aux_labels(aux):
    """label -> hyperref anchor, for every \\newlabel of the .aux."""
    out = {}
    for line in Path(aux).read_text(encoding='utf-8', errors='replace').splitlines():
        m = _NEWLABEL.match(line)
        if m:
            out[m[1]] = m[3]
    return out


def toc_targets(toc):
    out = set()
    for line in Path(toc).read_text(encoding='utf-8', errors='replace').splitlines():
        m = _TOC.match(line)
        if m:
            out.add(m[1])
    return out


def index_lines(index):
    """index term -> its line of the topic-index fragment."""
    out = {}
    for line in Path(index).read_text(encoding='utf-8').splitlines():
        m = re.match(r'^\*\*(.+?)\*\*: ', line)
        if m:
            out[m[1]] = line
    return out


def problems(book, report=None, registry=None, appendix=None, index=None):
    """Return (problems, stats) for the rendered book in `book`."""
    book = Path(book)
    report = Path(report) if report else book.parent
    registry = Path(registry) if registry else report / 'tools/reader-glossary.json'
    appendix = Path(appendix) if appendix else book / 'chapters/appendices/_apph-glossary.qmd'
    index = Path(index) if index else book / 'chapters/appendices/_appf-topic-index.qmd'
    aux, toc = book / 'index.aux', book / 'index.toc'
    missing = [p.name for p in (aux, toc, index) if not p.exists()]
    if missing:
        return [f'{", ".join(missing)} not found: the rendered-book gate needs a PDF render that keeps them'], {}
    labels, targets, lines = aux_labels(aux), toc_targets(toc), index_lines(index)
    entries = json.loads(registry.read_text(encoding='utf-8'))['entries']
    out, via_toc, via_index, own = [], 0, 0, 0
    for e in entries:
        section, name = e.get('section'), f'{e["kind"]} {e["term"]}'
        line = lines.get(f'`{e["term"]}`' if e['kind'] == 'key' else e['term'], '')
        has_entry = bool(section) and any(f'{a}{section}{b}' in line for a, b in (('@', '.'), ('@', ';'), ('(#', ')')))
        own += has_entry
        if not has_entry:
            out.append(f'{name}: no topic-index line of its own refers to its defining section {section}')
        if section not in labels:
            out.append(f'{name}: defining section {section} does not resolve in index.aux')
            continue
        if _ROLLUP.match(labels[section]):
            out.append(f'{name}: defining section {section} is a chapter or appendix heading ({labels[section]}), '
                       'a roll-up')
        if labels[section] in targets:
            via_toc += 1
        elif has_entry:
            via_index += 1
        else:
            out.append(f'{name}: defining section {section} is neither in the table of contents nor in the topic index')
    links = _LINK.findall(appendix.read_text(encoding='utf-8')) if appendix.exists() else []
    out += [f'glossary appendix link #{s} does not resolve in index.aux' for s in sorted(set(links)) if s not in labels]
    stats = dict(concepts=len(entries), via_toc=via_toc, via_topic_index=via_index, index_entries=own,
                 roll_ups=sum('a roll-up' in p for p in out), appendix_links=len(links),
                 unresolved=sum('does not resolve' in p for p in out))
    return out, stats


def check(book=None):
    book = Path(book) if book else REPORT / 'book'
    try:
        bad, stats = problems(book)
    except (OSError, ValueError, KeyError) as exc:
        bad, stats = [str(exc)], {}
    detail = (f'; {stats["concepts"]} concepts, {stats["via_toc"]} via the table of contents, '
              f'{stats["via_topic_index"]} via the topic index only, {stats["index_entries"]} with their own '
              f'topic-index entry, {stats["appendix_links"]} glossary links, '
              f'{stats["roll_ups"]} roll-ups, {stats["unresolved"]} unresolved') if stats else ''
    print(f'[N1/N4 rendered glossary] {len(bad)} problem(s){detail}')
    for p in bad[:20]:
        print('  ' + p)
    return int(bool(bad))


if __name__ == '__main__':
    sys.exit(check(sys.argv[1] if len(sys.argv) > 1 else None))
