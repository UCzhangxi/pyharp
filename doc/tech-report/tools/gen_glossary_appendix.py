"""Appendix H, the glossary, generated from the concept registry (tools/reader-glossary.json).

One entry per concept, grouped as acronyms, YAML keys and symbols: the term, its meaning (the text the first-use
notes print, tools/gen_reader_reference.py) and a link to its defining section, written as that section's title so
that unnumbered sections (the groups of Appendix A) read correctly. An entry the book does not define (marked
`not_defined_here` in the registry) says "Not defined here" and links the first section that uses it. Run before every render; `--check` fails when the
committed fragment is not a fresh generation or when a link names a section the book does not have.

usage: python3 tools/gen_glossary_appendix.py [--check]
"""
import re
import sys
from pathlib import Path

REPORT = Path(__file__).resolve().parent.parent
FRAGMENT = REPORT / 'book/chapters/appendices/_apph-glossary.qmd'
GROUPS = (('acronym', 'Acronyms'), ('key', 'YAML keys'), ('concept', 'Named concepts'), ('symbol', 'Symbols'))


def _tools():
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    import gen_reader_reference as reference
    import glossary_registry as registry
    return reference, registry


def _title(title):
    """A heading's text as link text: no trailing attribute braces, no nested links."""
    return re.sub(r'\[([^\]]*)\]\([^)]*\)', r'\1', title).strip()


def _where(item, book_labels):
    target = book_labels.get(item.get('section', ''))
    return f'[{_title(target["title"])}](#{item["section"]})' if target else f'`{item.get("section", "")}`'


def render(report=REPORT):
    import json
    reference, registry = _tools()
    data = json.loads((report / registry.REGISTRY).read_text(encoding='utf-8'))
    meanings = {(e['kind'], e['term']): e['meaning'] for e in reference.glossary_entries(report)}
    book_labels = registry.labels(report / 'book')
    lines = ['<!-- generated reader-reference: glossary-appendix -->',
             '<!-- Generated by tools/gen_glossary_appendix.py from tools/reader-glossary.json; do not edit. -->', '']
    for kind, heading in GROUPS:
        items = [i for i in data['entries'] if i['kind'] == kind]
        lines += [f'## {heading} {{.unnumbered .unlisted}}', '']
        for item in sorted(items, key=lambda i: re.sub(r'[^0-9a-z]', '', i['term'].lower()) or i['term']):
            term = item['term'] if kind == 'symbol' else f'`{item["term"]}`' if kind == 'key' else f'**{item["term"]}**'
            if kind == 'concept':  # a named concept carries no gloss of its own: the book's section is its meaning
                lines.append(f'- {term}: ' + (f'not defined here; used in {_where(item, book_labels)}.' if item.get(
                    registry.MARK) else f'defined in {_where(item, book_labels)}.'))
                continue
            section = item.get('section', '')
            target = book_labels.get(section)
            where = f'[{_title(target["title"])}](#{section})' if target else f'`{section}`'
            meaning = meanings[(kind, item['term'])].rstrip().rstrip('.')
            if not item.get(registry.MARK):
                lines.append(f'- {term}: {meaning}. Defined in {where}.')
            elif section == 'sec-apph':
                lines.append(f'- {term}: {meaning}. Not defined here; no chapter uses it.')
            else:
                lines.append(f'- {term}: {meaning}. Not defined here; used in {where}.')
        lines.append('')
    lines.append('<!-- end reader-reference: glossary-appendix -->')
    return '\n'.join(lines) + '\n'


def problems(report=REPORT, data=None):
    import json
    _, registry = _tools()
    if data is None:
        data = json.loads((report / registry.REGISTRY).read_text(encoding='utf-8'))
    book_labels = registry.labels(report / 'book')
    out = [f'{i["kind"]} {i["term"]}: link target {i.get("section")!r} is not a section of the book'
           for i in data['entries'] if i.get('section') not in book_labels]
    fragment = report / FRAGMENT.relative_to(REPORT)
    if not out and (not fragment.exists() or fragment.read_text(encoding='utf-8') != render(report)):
        out.append(f'{fragment.name} is stale; run python3 tools/gen_glossary_appendix.py')
    return out


def check(report=REPORT):
    try:
        bad = problems(Path(report))
    except (OSError, ValueError, KeyError) as exc:
        bad = [str(exc)]
    print(f'[N4 glossary appendix] {len(bad)} problem(s)')
    for p in bad:
        print('  ' + p)
    return int(bool(bad))


def main(argv):
    if '--check' in argv:
        return check(REPORT)
    FRAGMENT.write_text(render(REPORT), encoding='utf-8')
    print(f'gen_glossary_appendix: wrote {FRAGMENT}')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
