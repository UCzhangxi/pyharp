#!/usr/bin/env python3
"""Generate Appendix G, the task map, from the curated reader-task list tools/reader-tasks.md (STYLE N2).

The "How do I ...?" appendix is task-indexed and section-anchored. Every row of the list is one task a reader
wants to do, with the anchor of the section that answers it or `not provided: <status>: <reason>`. This script
checks the list against the book and writes one line per task, grouped by status:

  * a task's status is one of answered, partly documented, undocumented, unsupported by the code, outside scope.
    A not-provided row takes it from its reason ("content gap" and "not in the book" are undocumented). An
    anchored bank row (Q-...) keeps the status of its question in tools/task-map.yaml, the lookup grade; any
    anchored row whose note says "partly" or flags PARTIAL is at most partly documented. A pointer is not by
    itself evidence that a task is answered.
  * an anchor is a label of a heading of the book and never a chapter or appendix heading (a roll-up), with no
    exemption: a task whose answering section has no label needs one. An exemption list next to the data
    (tools/reader-tasks-findings.json) is itself a failure.
  * a not-provided row names a reason. The appendix prints the reason without the reviewer's evidence (lookup
    counts, source line numbers, review history in parentheses); bare `sec-` labels become references.

After a render, the rendered gate (`--rendered`) reads book/index.aux and book/index.toc: every anchor resolves to
a `\\newlabel` whose destination is a section, not a chapter or an appendix; and the text of the rendered PDF
(pdftotext) holds "Not provided:" followed by the reason of every not-provided row.

    python3 tools/gen_reader_tasks.py              # check, then rewrite the fragment
    python3 tools/gen_reader_tasks.py --check      # exit 1 on a problem or if the fragment is stale
    python3 tools/gen_reader_tasks.py --stats      # counts by status and kind
    python3 tools/gen_reader_tasks.py --rendered   # the gate on the rendered book
"""

from __future__ import annotations

import argparse
import re
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import gen_task_map as gtm  # noqa: E402  (the bank's lookup grades, headings of any level, references)

REPORT = Path(__file__).resolve().parent.parent
BOOK = REPORT / "book"
DATA = REPORT / "tools" / "reader-tasks.md"
FINDINGS = REPORT / "tools" / "reader-tasks-findings.json"
FRAGMENT = BOOK / "chapters" / "appendices" / "_appg-reader-tasks.qmd"
HEADER = ("<!-- GENERATED by tools/gen_reader_tasks.py from tools/reader-tasks.md and the section titles; "
          "do not edit. -->")
STATUSES = gtm.STATUSES
NP_STATUS = {"undocumented": "undocumented", "content gap": "undocumented", "not in the book": "undocumented",
             "unsupported by the code": "unsupported by the code", "outside scope": "outside scope"}
_NP = re.compile(r"not provided: ([a-z ]+?): (.*)$")
_PARTIAL = re.compile(r"\bpartly\b|FLAG[^;]*\bPARTIAL\b")
# the reviewer's evidence inside a reason: lookup counts, source lines and review history
_EVIDENCE = re.compile(r"\s*\((?:[^()]*?(?:lookup|\bhits?\b|agreed out|scope test|\.qmd:\d)[^()]*)\)"
                       r"|;\s*lookup:[^;]*|;?\s*\(?agreed out\)?")
_ROLLUP_AUX = re.compile(r"^(chapter|appendix)\.[A-Z0-9]+$")


# --- the list ---------------------------------------------------------------------------------------------------

def load(text: str) -> list[dict]:
    """The rows of the task table: id, task, sources, anchor or not-provided text, note."""
    rows = []
    for n, line in enumerate(text.splitlines(), 1):
        if not line.startswith("| ") or line.startswith("| id ") or set(line) <= set("|- "):
            continue
        cells = [c.strip().replace("\\|", "|") for c in re.split(r"(?<!\\)\|", line.strip())[1:-1]]
        if len(cells) != 5:
            raise ValueError(f"line {n}: {len(cells)} columns, not 5")
        rows.append(dict(zip(("id", "task", "sources", "where", "note"), cells), line=n))
    return rows


def status(row: dict, bank: dict[str, dict]) -> str | None:
    m = _NP.match(row["where"])
    if row["where"].startswith("not provided"):
        return NP_STATUS.get(m[1]) if m else None
    parent = bank.get(row["id"][:5]) if row["id"].startswith("Q-") else None
    st = parent["status"] if parent and parent.get("status") in ("answered", "partly documented") else (
        "partly documented" if parent else "answered")
    return "partly documented" if _PARTIAL.search(row["note"]) else st


def reason(row: dict) -> str:
    """The reader's reason of a not-provided row: no status prefix and no reviewer's evidence."""
    m = _NP.match(row["where"])
    text = _EVIDENCE.sub("", m[2]) if m else ""
    text = re.sub(r"\(\s*\)", "", text).strip(" ;,.")
    return re.sub(r"(?<![@#\w-])(sec-[A-Za-z0-9_-]*[A-Za-z0-9])", r"@\1", text)


def bank_records(report: Path) -> dict[str, dict]:
    path = report / "tools" / "task-map.yaml"
    return {t["id"]: t for t in gtm.load(path.read_text(encoding="utf-8"))["tasks"]} if path.exists() else {}


def rollup(label: str, labs: dict[str, dict], book: Path) -> bool:
    """A chapter or appendix heading (`# ...`), whose section is the whole chapter."""
    h = labs.get(label)
    if not h:
        return False
    for line in (book / h["file"]).read_text(encoding="utf-8").splitlines():
        if re.match(r"^# .*\{[^{}]*#%s[\s}]" % re.escape(label), line):
            return True
    return False


# --- checks -----------------------------------------------------------------------------------------------------

def problems(rows: list[dict], labs: dict[str, dict], book: Path, bank: dict[str, dict]) -> list[str]:
    out = []
    if (Path(book).absolute().parent / "tools" / FINDINGS.name).exists():
        out.append(f"{FINDINGS.name}: roll-up targets have no exemption; label the answering sections and delete it")
    ids = [r["id"] for r in rows]
    for i in sorted({i for i in ids if ids.count(i) > 1}):
        out.append(f"{i}: listed {ids.count(i)} times")
    for r in rows:
        if not r["task"]:
            out.append(f"{r['id']}: no task")
        if status(r, bank) not in STATUSES:
            out.append(f"{r['id']}: no status; a not-provided row reads `not provided: <status>: <reason>` with a "
                       f"status of: {', '.join(NP_STATUS)}")
        if r["where"].startswith("not provided"):
            if not reason(r):
                out.append(f"{r['id']}: not provided, but no reason")
        elif not re.fullmatch(r"sec-[A-Za-z0-9_-]+", r["where"]):
            out.append(f"{r['id']}: column 4 is neither a label nor `not provided: ...`")
        elif r["where"] not in labs:
            out.append(f"{r['id']}: anchor {r['where']} is not a label of the book")
        elif rollup(r["where"], labs, book):
            out.append(f"{r['id']}: anchor {r['where']} is a chapter or appendix roll-up; label the answering "
                       "section and anchor the row there")
    return out


def counts(rows: list[dict], bank: dict[str, dict]) -> dict[str, int]:
    c = {s: 0 for s in STATUSES}
    for r in rows:
        if status(r, bank) in c:
            c[status(r, bank)] += 1
    return c


# --- the fragment -----------------------------------------------------------------------------------------------

def render(rows: list[dict], labs: dict[str, dict], bank: dict[str, dict]) -> str:
    c = counts(rows, bank)
    out = [HEADER, "", "| status | tasks |", "|---|---|"]
    out += [f"| {s} | {c[s]} |" for s in STATUSES]
    out += [f"| total | {sum(c.values())} |", "", ": Reader tasks by status. {#tbl-appg-reader-tasks}", ""]
    for s in STATUSES:
        mine = [r for r in rows if status(r, bank) == s]
        if not mine:
            continue
        out += [f"## {s[0].upper() + s[1:]} {{.unnumbered .unlisted}}", ""]
        for r in mine:
            task = r["task"].rstrip(".")
            if r["where"].startswith("not provided"):
                out.append(f"- {task}. Not provided: {reason(r)}.")
            else:
                out.append(f"- {task}. See {gtm._ref(r['where'], labs)}.")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


# --- the rendered book ------------------------------------------------------------------------------------------

def aux_destinations(aux: Path) -> dict[str, str]:
    """label -> hyperref destination of every \\newlabel of the .aux."""
    out = {}
    for line in aux.read_text(encoding="utf-8", errors="replace").splitlines():
        m = re.match(r"^\\newlabel\{([^}]+)\}\{\{.*\}\{([^{}]*)\}\{\}\}\s*$", line)
        if m:
            out[m[1]] = m[2]
    return out


def _letters(text: str) -> str:
    """Lower-case letters and digits only, so line breaks and hyphenation of the PDF text do not matter."""
    return re.sub(r"[^0-9a-z]+", "", text.lower())


def pdf_text(book: Path) -> str | None:
    """The text of the rendered PDF (book/_book/*.pdf, pdftotext), or None when there is none."""
    import shutil
    import subprocess
    pdfs = sorted((book / "_book").glob("*.pdf"))
    if not pdfs or not shutil.which("pdftotext"):
        return None
    out = subprocess.run(["pdftotext", str(pdfs[0]), "-"], capture_output=True, text=True, check=True).stdout
    return strip_page_furniture(out)


_PAGE_NUMBER = re.compile(r"\d+|[ivxlcdm]+", re.IGNORECASE)


def strip_page_furniture(text: str) -> str:
    """pdftotext text without the furniture at each page break (\\f), so a sentence that crosses a page reads on:
    the page number, when it is the last line before the break, and the running head, when the first line after
    the break is printed again elsewhere in the text (on another page's head or as a heading of the body) and is
    no page number. A body line at the top of a page that the text prints only once is kept."""
    pages = [p.split("\n") for p in text.split("\f")]
    count = Counter(line.strip() for page in pages for line in page if line.strip())

    def first(lines, order):
        return next((i for i in order if lines[i].strip()), None)

    for k, lines in enumerate(pages):
        if k + 1 < len(pages):
            i = first(lines, range(len(lines) - 1, -1, -1))
            if i is not None and _PAGE_NUMBER.fullmatch(lines[i].strip()):
                del lines[i]
        if k > 0:
            i = first(lines, range(len(lines)))
            if i is not None and count[lines[i].strip()] > 1 and not _PAGE_NUMBER.fullmatch(lines[i].strip()):
                del lines[i]
    return "\f".join("\n".join(lines) for lines in pages)


def printed_reason(r: dict) -> str:
    """What the PDF must show for a not-provided row: "Not provided:" and its reason up to the first reference,
    code or maths, whose rendered form differs from the source."""
    return _letters("Not provided: " + re.split(r"[@`$]", reason(r))[0])


def rendered_problems(book: Path, rows: list[dict], bank: dict[str, dict],
                      text: str | None = None) -> tuple[list[str], dict]:
    aux, toc = book / "index.aux", book / "index.toc"
    text = pdf_text(book) if text is None else text
    missing = [p.name for p in (aux, toc) if not p.exists()] + ([] if text is not None else ["the PDF (pdftotext)"])
    if missing:
        return [f"{', '.join(missing)} not found: the rendered gate needs a PDF render that keeps them"], {}
    dest = aux_destinations(aux)
    toc_text = toc.read_text(encoding="utf-8", errors="replace")
    printed = _letters(text)
    out, stats = [], dict(rows=len(rows), anchored=0, not_provided=0, in_toc=0, roll_ups=0, unresolved=0)
    for r in rows:
        if r["where"].startswith("not provided"):
            stats["not_provided"] += 1
            if not reason(r) or printed_reason(r) not in printed:
                out.append(f"{r['id']}: not provided, but the rendered PDF prints no reason")
            continue
        stats["anchored"] += 1
        lab = r["where"]
        if lab not in dest:
            stats["unresolved"] += 1
            out.append(f"{r['id']}: anchor {lab} does not resolve in index.aux")
        elif _ROLLUP_AUX.match(dest[lab]):
            stats["roll_ups"] += 1
            out.append(f"{r['id']}: anchor {lab} lands on {dest[lab]}, a chapter or appendix roll-up")
        elif "{%s}" % dest[lab] in toc_text:
            stats["in_toc"] += 1
    return out, stats


def subprocess_error():
    import subprocess
    return subprocess.CalledProcessError


def check_rendered(book: Path = BOOK, report: Path = REPORT) -> int:
    if not (report / "tools" / DATA.name).exists():
        print(f"[N2 rendered task map] no tools/{DATA.name} next to the book: skipped")
        return 0
    try:
        rows = load((report / "tools" / DATA.name).read_text(encoding="utf-8"))
        bad, stats = rendered_problems(book, rows, bank_records(report))
    except (OSError, ValueError, KeyError, subprocess_error()) as exc:
        bad, stats = [str(exc)], {}
    detail = (f"; {stats['rows']} tasks, {stats['anchored']} anchored ({stats['in_toc']} in the table of contents, "
              f"{stats['roll_ups']} roll-ups), {stats['not_provided']} not provided with a printed reason, "
              f"{stats['unresolved']} unresolved") if stats else ""
    print(f"[N2 rendered task map] {len(bad)} problem(s){detail}")
    for p in bad[:20]:
        print("  " + p)
    return int(bool(bad))


def check(report: Path = REPORT, book: Path | None = None) -> int:
    """The source gate: the list against the book, no exemption list, and a fresh fragment."""
    book = book or report / "book"
    if not (report / "tools" / DATA.name).exists():
        print(f"[N2 reader tasks] no tools/{DATA.name} next to the book: skipped")
        return 0
    try:
        rows = load((report / "tools" / DATA.name).read_text(encoding="utf-8"))
        bank, labs = bank_records(report), gtm.labels(book)
        bad = problems(rows, labs, book, bank)
        frag = book / "chapters" / "appendices" / FRAGMENT.name
        if not bad and (not frag.exists() or frag.read_text(encoding="utf-8") != render(rows, labs, bank)):
            bad.append(f"{frag.name} is stale; run python3 tools/gen_reader_tasks.py")
    except (OSError, ValueError, KeyError) as exc:
        bad, rows = [str(exc)], []
    print(f"[N2 reader tasks] {len(bad)} problem(s); {len(rows)} tasks")
    for p in bad:
        print("  " + p)
    return int(bool(bad))


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--stats", action="store_true")
    mode.add_argument("--rendered", action="store_true")
    args = ap.parse_args(argv)
    if args.check:
        return check()
    if args.rendered:
        return check_rendered()
    rows, bank = load(DATA.read_text(encoding="utf-8")), bank_records(REPORT)
    if args.stats:
        c = counts(rows, bank)
        print(", ".join(f"{s} {c[s]}" for s in STATUSES) + f" (total {sum(c.values())}); "
              f"{sum(not r['where'].startswith('not provided') for r in rows)} anchored, "
              f"{sum(r['where'].startswith('not provided') for r in rows)} not provided")
        return 0
    labs = gtm.labels(BOOK)
    bad = problems(rows, labs, BOOK, bank)
    for p in bad:
        print(f"gen_reader_tasks: {p}", file=sys.stderr)
    if bad:
        return 1
    FRAGMENT.write_text(render(rows, labs, bank), encoding="utf-8")
    print(f"gen_reader_tasks: wrote {FRAGMENT}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
