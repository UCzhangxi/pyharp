#!/usr/bin/env python3
"""Generate Appendix G, the task map, from tools/task-map.yaml (STYLE "Reader standards", N2).

Every question of the newcomer question bank gets one record in `tools/task-map.yaml`: its status (answered,
partly documented, undocumented, unsupported by the code, outside scope) and either the section that answers it
best or the reason the book does not. This script turns the file into "How do I ...?" lists, one per status, with
the counts, and checks it first:

  * every id of `bank_ids` (a range such as `Q-001..Q-095`) appears exactly once, and no other id appears; before the
    bank exists, `bank_ids: ''` with `tasks: []` is the valid empty map;
  * a status is one of the five;
  * a record has exactly one of `dest` and `not_provided`, and a question;
  * a `dest` is a label (`{#sec-...}`) of a heading of the book.

    python3 tools/gen_task_map.py           # check, then rewrite the fragment
    python3 tools/gen_task_map.py --check   # exit 1 on a problem or if the fragment is stale
    python3 tools/gen_task_map.py --stats   # the status counts

Only the Python standard library is needed: `load` reads the subset of YAML the file uses (tools/tests/
test_task_map.py compares it with a full YAML reader). Exit status 0 on success, 1 on a problem or a stale fragment.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import gen_topic_index as gti  # noqa: E402  (book headings, plain titles, numbering)

REPORT = Path(__file__).resolve().parent.parent
BOOK = REPORT / "book"
DATA = REPORT / "tools" / "task-map.yaml"
FRAGMENT = BOOK / "chapters" / "appendices" / "_appg-task-map.qmd"
HEADER = "<!-- GENERATED by tools/gen_task_map.py from tools/task-map.yaml and the section titles; do not edit. -->"
STATUSES = ("answered", "partly documented", "undocumented", "unsupported by the code", "outside scope")
_ID = re.compile(r"Q-(\d+)")


# --- the data file ----------------------------------------------------------------------------------------------

def _scalar(s: str) -> str:
    s = s.strip()
    if len(s) >= 2 and s[0] == s[-1] == "'":
        return s[1:-1].replace("''", "'")
    if len(s) >= 2 and s[0] == s[-1] == '"':
        return bytes(s[1:-1], "utf-8").decode("unicode_escape").encode("latin-1").decode("utf-8")
    return s


def load(text: str) -> dict:
    """Read task-map.yaml: `bank_ids` (str) and `tasks` (list of maps of str). Raises ValueError on other layouts."""
    data: dict = {"bank_ids": None, "tasks": []}
    top = None
    for n, raw in enumerate(text.splitlines(), 1):
        if not raw.strip() or raw.lstrip().startswith("#"):
            continue
        if not raw.startswith((" ", "-")):
            key, _, value = raw.partition(":")
            if key == "bank_ids":
                data["bank_ids"] = _scalar(value)
            elif key == "tasks" and value.strip() in ("", "[]"):
                top = "tasks"
            else:
                raise ValueError(f"line {n}: unknown top-level key {key!r}")
        elif top == "tasks" and raw.startswith("- "):
            k, _, v = raw[2:].partition(": ")
            data["tasks"].append({k.strip(): _scalar(v)})
        elif top == "tasks" and raw.startswith("  ") and data["tasks"]:
            k, _, v = raw.strip().partition(": ")
            if not v and not raw.rstrip().endswith(":"):
                raise ValueError(f"line {n}: expected `key: value`")
            data["tasks"][-1][k.strip()] = _scalar(v)
        else:
            raise ValueError(f"line {n}: unexpected {raw.strip()!r}")
    return data


def bank_range(spec: str | None) -> list[str]:
    m = re.fullmatch(r"Q-(\d+)\.\.Q-(\d+)", (spec or "").strip())
    if not m:
        return []
    width = len(m[1])
    return [f"Q-{i:0{width}d}" for i in range(int(m[1]), int(m[2]) + 1)]


# --- the book ---------------------------------------------------------------------------------------------------

_ANY_HEADING = re.compile(r"^(#{1,6}) (.*?)\s*\{([^{}]*#(sec-[\w-]+)[^{}]*)\}\s*$")


def labels(book: Path) -> dict[str, dict]:
    """Every labelled heading of the book, any level: label -> {title, file, classes, numbered}."""
    out = {}
    for q in book.rglob("*.qmd"):
        rel = q.relative_to(book).as_posix()
        if rel.startswith(("_", ".")):
            continue
        fence = False
        for line in q.read_text(encoding="utf-8").splitlines():
            if line.lstrip().startswith("```"):
                fence = not fence
                continue
            m = None if fence else _ANY_HEADING.match(line)
            if m:
                classes = set(re.findall(r"\.([\w-]+)", m[3]))
                out[m[4]] = {"title": m[2].strip(), "file": rel, "classes": classes,
                             "numbered": "unnumbered" not in classes and rel != "index.qmd"}
    return out


# --- checks -----------------------------------------------------------------------------------------------------

def problems(data: dict, labs: dict[str, dict]) -> list[str]:
    out = []
    want = bank_range(data.get("bank_ids"))
    if not want and (data.get("bank_ids") or "").strip():
        out.append(f"bank_ids {data.get('bank_ids')!r} is not a range such as Q-001..Q-095")
    ids = [t.get("id", "") for t in data.get("tasks") or []]
    for i in want:
        if ids.count(i) == 0:
            out.append(f"{i}: bank question has no record")
    for i in sorted({i for i in ids if ids.count(i) > 1}):
        out.append(f"{i}: listed {ids.count(i)} times")
    for i in sorted(set(ids) - set(want)):
        out.append(f"{i or '(no id)'}: not an id of the bank range {data.get('bank_ids')}")
    for t in data.get("tasks") or []:
        tid = t.get("id", "(no id)")
        if t.get("status") not in STATUSES:
            out.append(f"{tid}: status {t.get('status')!r} is not one of: {', '.join(STATUSES)}")
        if not t.get("question"):
            out.append(f"{tid}: no question")
        if bool(t.get("dest")) == bool(t.get("not_provided")):
            out.append(f"{tid}: needs exactly one of dest and not_provided")
        if t.get("dest") and t["dest"] not in labs:
            out.append(f"{tid}: dest {t['dest']} is not a label of the book")
    return out


def counts(data: dict) -> dict[str, int]:
    c = {s: 0 for s in STATUSES}
    for t in data.get("tasks") or []:
        if t.get("status") in c:
            c[t["status"]] += 1
    return c


# --- the fragment -----------------------------------------------------------------------------------------------

def _ref(label: str, labs: dict[str, dict]) -> str:
    h = labs[label]
    title = gti.plain_title(h["title"])
    return f"{title}, @{label}" if h["numbered"] else f"[{title}](#{label})"


def render(data: dict, labs: dict[str, dict]) -> str:
    c = counts(data)
    out = [HEADER, "", "| status | questions |", "|---|---|"]
    out += [f"| {s} | {c[s]} |" for s in STATUSES]
    out += [f"| total | {sum(c.values())} |", "", ": Questions of the bank by status. {#tbl-appg-status}", ""]
    tasks = sorted(data.get("tasks") or [], key=lambda t: int(_ID.fullmatch(t["id"])[1]))
    for s in STATUSES:
        rows = [t for t in tasks if t.get("status") == s]
        if not rows:
            continue
        out += [f"## {s[0].upper() + s[1:]} {{.unnumbered .unlisted}}", ""]
        for t in rows:
            line = f"**{t['id']}.** {t['question']}"
            if t.get("dest"):
                where = _ref(t["dest"], labs)
                if t.get("best_section_unlabeled"):
                    where = f"{t['best_section_unlabeled']}, in {where}"
                line += f" See {where}."
                if t.get("missing"):
                    line += f" Not covered: {t['missing'].rstrip('.')}."
            else:
                line += f" Not provided: {t['not_provided'].rstrip('.')}."
            out += [line, ""]
    return "\n".join(out).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--stats", action="store_true")
    ap.add_argument("--data", type=Path, default=DATA)
    ap.add_argument("--book", type=Path, default=BOOK)
    ap.add_argument("--fragment", type=Path, default=None)
    args = ap.parse_args(argv)
    frag = args.fragment or args.book / "chapters" / "appendices" / "_appg-task-map.qmd"
    try:
        data = load(args.data.read_text(encoding="utf-8"))
    except ValueError as e:
        print(f"gen_task_map: {args.data}: {e}", file=sys.stderr)
        return 1
    if args.stats:
        c = counts(data)
        print(", ".join(f"{s} {c[s]}" for s in STATUSES) + f" (total {sum(c.values())})")
        return 0
    labs = labels(args.book)
    bad = problems(data, labs)
    for p in bad:
        print(f"gen_task_map: {p}", file=sys.stderr)
    if bad:
        print(f"gen_task_map: FAIL, {len(bad)} problem(s) in {args.data.name}", file=sys.stderr)
        return 1
    want = render(data, labs)
    have = frag.read_text(encoding="utf-8") if frag.exists() else None
    if args.check:
        if have != want:
            print(f"gen_task_map: {frag.name} is stale; run python3 tools/gen_task_map.py", file=sys.stderr)
            return 1
        print("gen_task_map: 1 generated file(s) are current", file=sys.stderr)
        return 0
    if have != want:
        frag.parent.mkdir(parents=True, exist_ok=True)
        frag.write_text(want, encoding="utf-8")
    print(f"gen_task_map: wrote {frag}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
