#!/usr/bin/env python3
"""Generate Appendix F, the topic index, from tools/topic-index.yaml (STYLE "Reader standards", N1).

Every labelled `##` section of the book gets index terms in the reader's own words in `tools/topic-index.yaml`;
the chapters carry no index markup. This script turns that file into an alphabetical index: one line per term,
with a reference to every section that lists it (book order), and one "see" line per alias. A numbered section
is cited as its title plus `@sec-...`, an unnumbered one (the preface, the groups of Appendix A) as a link. A term
whose answer is a whole chapter or appendix with no `##` sections of its own (the test index, Appendix C) may
also be listed under that chapter's `#` label.
Every concept of the registry, `tools/reader-glossary.json` (acronyms, YAML keys, symbols), also gets its own
line, which refers to its registry defining section and to no other (STYLE N1).

It also checks the file against the book and stops the render on a problem:

  * a label in the file that no `#` or `##` heading of the book carries;
  * a labelled `##` section with no term (the reader could not find it from the index);
  * a `##` heading with no label that is neither a `.unlisted` part divider nor listed under `unlabeled`, and an
    `unlabeled` row that matches no heading or names a label that does not exist;
  * an alias that is also a term, or a term listed twice for one section.

    python3 tools/gen_topic_index.py           # check, then rewrite the fragment
    python3 tools/gen_topic_index.py --check   # exit 1 on a problem or if the fragment is stale
    python3 tools/gen_topic_index.py --stats   # sections, terms, aliases and references

Only the Python standard library is needed: the file is read by `load`, which accepts the subset of YAML the
file uses (tools/tests/test_topic_index.py compares it with a full YAML reader). Exit status 0 on success, 1 on a
problem or a stale fragment.
"""

from __future__ import annotations

import argparse
import fnmatch
import re
import sys
from pathlib import Path

REPORT = Path(__file__).resolve().parent.parent
BOOK = REPORT / "book"
DATA = REPORT / "tools" / "topic-index.yaml"
FRAGMENT = BOOK / "chapters" / "appendices" / "_appf-topic-index.qmd"
HEADER = ("<!-- GENERATED by tools/gen_topic_index.py from tools/topic-index.yaml, tools/reader-glossary.json "
          "and the section titles; do not edit. -->")

_HEADING = re.compile(r"^(#{1,2}) (.*?)\s*$")
_ATTRS = re.compile(r"\s*\{([^{}]*)\}\s*$")
_LABEL = re.compile(r"#(sec-[\w-]+)")


# --- the data file ----------------------------------------------------------------------------------------------

def _scalar(s: str) -> str:
    s = s.strip()
    return s[1:-1] if len(s) >= 2 and s[0] == s[-1] and s[0] in "\"'" else s


def load(text: str) -> dict:
    """Read topic-index.yaml: `sections` (label -> list of str or {term: [aliases]}) and `unlabeled` (list of maps).

    Accepts exactly the layout the file uses: two top-level keys, two-space indentation, `- term` or
    `- term: [alias, alias]` items, and `- key: value` maps with continuation lines. Raises ValueError otherwise.
    """
    data: dict = {"sections": {}, "unlabeled": []}
    top = label = None
    for n, raw in enumerate(text.splitlines(), 1):
        line = raw.split(" #", 1)[0].rstrip() if not raw.lstrip().startswith("#") else ""
        if not line.strip():
            continue
        indent = len(line) - len(line.lstrip())
        body = line.strip()
        if indent == 0:
            if body not in ("sections:", "unlabeled:"):
                raise ValueError(f"line {n}: unknown top-level key {body!r}")
            top = body[:-1]
        elif top == "sections" and indent == 2 and body.endswith(":") and not body.startswith("-"):
            label = body[:-1]
            if label in data["sections"]:
                raise ValueError(f"line {n}: {label} listed twice")
            data["sections"][label] = []
        elif top == "sections" and indent == 4 and body.startswith("- ") and label:
            item = body[2:]
            m = re.fullmatch(r"(.+?):\s*\[(.*)\]", item)
            if m:
                data["sections"][label].append({_scalar(m[1]): [_scalar(a) for a in m[2].split(",") if a.strip()]})
            elif ":" in item.replace("::", ""):
                raise ValueError(f"line {n}: a term with ':' must have an alias list")
            else:
                data["sections"][label].append(_scalar(item))
        elif top == "unlabeled" and indent == 2 and body.startswith("- "):
            k, _, v = body[2:].partition(":")
            data["unlabeled"].append({k.strip(): _scalar(v)})
        elif top == "unlabeled" and indent == 4 and data["unlabeled"]:
            k, _, v = body.partition(":")
            data["unlabeled"][-1][k.strip()] = _scalar(v)
        else:
            raise ValueError(f"line {n}: unexpected {raw.strip()!r}")
    return data


def items(entries: list) -> list[tuple[str, list[str]]]:
    """(term, aliases) for every item of one section."""
    out = []
    for e in entries:
        if isinstance(e, dict):
            (term, aliases), = e.items()
            out.append((str(term), [str(a) for a in aliases or []]))
        else:
            out.append((str(e), []))
    return out


# --- the book ---------------------------------------------------------------------------------------------------

_INCLUDE = re.compile(r"^\{\{<\s*include\s+(\S+)\s*>\}\}\s*$")
_LISTED = re.compile(r"^\s*-\s+(\S+\.qmd)\s*$")


def book_order(book: Path) -> list[Path]:
    """The .qmd files in reading order: the chapter list of `_quarto.yml`, each file followed by its includes."""
    cfg = book / "_quarto.yml"
    listed = [book / m[1] for m in map(_LISTED.match, cfg.read_text().splitlines()) if m] if cfg.exists() else []
    seen: list[Path] = []

    def walk(q: Path) -> None:
        if q in seen or not q.exists():
            return
        seen.append(q)
        for line in q.read_text(encoding="utf-8").splitlines():
            m = _INCLUDE.match(line.strip())
            if m:
                walk((q.parent / m[1]).resolve())

    for q in listed:
        walk(q.resolve())
    return seen


def headings(book: Path) -> list[dict]:
    """Every `#`/`##` heading outside code fences, in book order (files not in the book last): file (relative to
    book/), line, level, title, label, classes."""
    out = []
    book = book.resolve()
    ordered = book_order(book)
    for q in ordered + sorted(q for q in book.rglob("*.qmd") if q.resolve() not in ordered):
        rel = q.relative_to(book).as_posix()
        if rel.startswith(("_", ".")) or "/_freeze/" in f"/{rel}" or rel.startswith("_site"):
            continue
        fence = False
        for n, line in enumerate(q.read_text(encoding="utf-8").splitlines(), 1):
            if line.lstrip().startswith("```"):
                fence = not fence
                continue
            m = _HEADING.match(line)
            if fence or not m:
                continue
            title, attrs = m[2], ""
            a = _ATTRS.search(title)
            if a:
                title, attrs = title[:a.start()], a[1]
            lab = _LABEL.search(attrs)
            out.append({"file": rel, "line": n, "level": len(m[1]), "title": title.strip(),
                        "label": lab[1] if lab else None, "classes": set(re.findall(r"\.([\w-]+)", attrs)),
                        "order": len(out)})
    return out


def plain_title(title: str) -> str:
    """The section title without a trailing parenthesis that names code (`(...)` holding backticks or PYHARP_)."""
    t = title.strip()
    if t.endswith(")"):
        depth = 0
        for i in range(len(t) - 1, -1, -1):
            depth += {")": 1, "(": -1}.get(t[i], 0)
            if depth == 0:
                inner = t[i + 1:-1]
                if "`" in inner or "PYHARP_" in inner:
                    t = t[:i].rstrip()
                break
    return t.rstrip(":;, ")


def numbered(h: dict, book: Path) -> bool:
    return "unnumbered" not in h["classes"] and h["file"] != "index.qmd"


# --- checks -----------------------------------------------------------------------------------------------------

def problems(data: dict, heads: list[dict]) -> list[str]:
    out = []
    sections = {h["label"]: h for h in heads if h["level"] == 2 and h["label"]}
    targets = {h["label"] for h in heads if h["level"] <= 2 and h["label"]}
    labels = {h["label"] for h in heads if h["label"]}
    entries = data.get("sections") or {}
    for label, ents in entries.items():
        if label not in targets:
            out.append(f"{label}: no `#` or `##` heading of the book has this label")
        its = items(ents or [])
        if not its:
            out.append(f"{label}: no index term")
        terms = [t for t, _ in its]
        for t in sorted({t for t in terms if terms.count(t) > 1}):
            out.append(f"{label}: term {t!r} listed twice")
    for label, h in sections.items():
        if label not in entries:
            out.append(f"{h['file']}:{h['line']}: section {label} ({plain_title(h['title'])}) has no index entry")
    all_terms = {t for ents in entries.values() for t, _ in items(ents or [])}
    for ents in entries.values():
        for t, aliases in items(ents or []):
            for a in aliases:
                if a in all_terms:
                    out.append(f"alias {a!r} of {t!r} is also a term; make it one or the other")
    rows = data.get("unlabeled") or []
    used = [False] * len(rows)
    for h in heads:
        if h["level"] != 2 or h["label"] or "unlisted" in h["classes"]:
            continue
        hit = [i for i, r in enumerate(rows) if fnmatch.fnmatch(h["file"], r.get("file", ""))
               and (r.get("heading") == "*" or r.get("heading") == h["title"])]
        for i in hit:
            used[i] = True
        if not hit:
            out.append(f"{h['file']}:{h['line']}: `## {h['title']}` has no label and is not listed under unlabeled")
    for r, u in zip(rows, used):
        if not u:
            out.append(f"unlabeled: {r.get('file')} `{r.get('heading')}` matches no heading")
        if r.get("covered-by") not in labels:
            out.append(f"unlabeled: covered-by {r.get('covered-by')!r} is not a label of the book")
    return out


# --- the fragment -----------------------------------------------------------------------------------------------

def _key(term: str) -> tuple[str, str]:
    k = re.sub(r"[^0-9a-z]+", " ", term.lower()).strip()
    return k, term


def _ref(h: dict, book: Path) -> str:
    title = plain_title(h["title"])
    return f"{title}, @{h['label']}" if numbered(h, book) else f"[{title}](#{h['label']})"


def concepts(registry: Path) -> list[tuple[str, str]]:
    """(index term, defining-section label) of every registry concept: an acronym as written, a key in code font,
    a symbol as its maths."""
    import json
    if not registry.exists():
        return []
    out = []
    for e in json.loads(registry.read_text(encoding="utf-8"))["entries"]:
        term = f"`{e['term']}`" if e["kind"] == "key" else e["term"]
        out.append((term, e.get("section", "")))
    return out


def labelled(book: Path) -> dict[str, dict]:
    """Every labelled heading of any level, as `headings` describes one (title, level, classes, file)."""
    out = {}
    book = book.resolve()
    for q in sorted(book.rglob("*.qmd")):
        rel = q.relative_to(book).as_posix()
        if rel.startswith(("_", ".")) or "/_freeze/" in f"/{rel}":
            continue
        fence = False
        for n, line in enumerate(q.read_text(encoding="utf-8").splitlines(), 1):
            if line.lstrip().startswith("```"):
                fence = not fence
                continue
            m = None if fence else re.match(r"^(#{1,6}) (.*?)\s*$", line)
            a = _ATTRS.search(m[2]) if m else None
            lab = _LABEL.search(a[1]) if a else None
            if lab:
                out[lab[1]] = {"file": rel, "line": n, "level": len(m[1]), "title": m[2][:a.start()].strip(),
                               "label": lab[1], "classes": set(re.findall(r"\.([\w-]+)", a[1]))}
    return out


def concept_problems(pairs: list[tuple[str, str]], labs: dict[str, dict]) -> list[str]:
    return [f"concept {t}: defining section {s!r} is not a label of the book" for t, s in pairs if s not in labs]


def render(data: dict, heads: list[dict], book: Path, pairs: list[tuple[str, str]] = (),
           labs: dict[str, dict] | None = None) -> str:
    sections = {h["label"]: h for h in heads if h["level"] <= 2 and h["label"]}
    refs: dict[str, list[dict]] = {}
    see: dict[str, set[str]] = {}
    for label, ents in (data.get("sections") or {}).items():
        for term, aliases in items(ents or []):
            if label in sections and sections[label] not in refs.setdefault(term, []):
                refs[term].append(sections[label])
            for a in aliases:
                see.setdefault(a, set()).add(term)
    lines = {}
    for term, hs in refs.items():
        hs = sorted(hs, key=lambda h: h["order"])
        lines[term] = f"**{term}**: " + "; ".join(_ref(h, book) for h in hs) + "."
    for term, label in pairs:
        if labs and label in labs:
            ref = _ref(labs[label], book)
            lines[term] = (lines[term][:-1] + "; " + ref + "." if term in lines and ref not in lines[term]
                           else lines.get(term, f"**{term}**: {ref}."))
    for alias, terms in see.items():
        targets = "; ".join(f"**{t}**" for t in sorted(terms, key=_key))
        if alias in lines:  # a registry concept that is also an alias keeps its pointer
            lines[alias] += f" See also {targets}."
        else:
            lines[alias] = f"*{alias}*, see {targets}."
    out = [HEADER, ""]
    letter = None
    for term in sorted(lines, key=_key):
        first = _key(term)[0][:1].upper()
        head = first if first.isalpha() else "0–9"
        if head != letter:
            letter = head
            out += [f"## {head} {{.unnumbered .unlisted}}", ""]
        out += [lines[term], ""]
    return "\n".join(out).rstrip() + "\n"


def stats(data: dict, heads: list[dict]) -> dict:
    its = [it for ents in (data.get("sections") or {}).values() for it in items(ents or [])]
    return {"sections": len(data.get("sections") or {}),
            "labelled ## sections in the book": sum(1 for h in heads if h["level"] == 2 and h["label"]),
            "items": len(its), "distinct terms": len({t for t, _ in its}),
            "aliases": len({a for _, al in its for a in al}),
            "unlabeled rows": len(data.get("unlabeled") or [])}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--stats", action="store_true")
    ap.add_argument("--data", type=Path, default=DATA)
    ap.add_argument("--book", type=Path, default=BOOK)
    ap.add_argument("--fragment", type=Path, default=None)
    args = ap.parse_args(argv)
    frag = args.fragment or args.book / "chapters" / "appendices" / "_appf-topic-index.qmd"
    try:
        data = load(args.data.read_text(encoding="utf-8"))
    except ValueError as e:
        print(f"gen_topic_index: {args.data}: {e}", file=sys.stderr)
        return 1
    heads = headings(args.book)
    pairs = concepts(args.data.parent / "reader-glossary.json")
    labs = labelled(args.book) if pairs else {}
    if args.stats:
        for k, v in stats(data, heads).items():
            print(f"{k}: {v}")
        return 0
    bad = problems(data, heads) + concept_problems(pairs, labs)
    for p in bad:
        print(f"gen_topic_index: {p}", file=sys.stderr)
    if bad:
        print(f"gen_topic_index: FAIL, {len(bad)} problem(s) in {args.data.name}", file=sys.stderr)
        return 1
    want = render(data, heads, args.book, pairs, labs)
    have = frag.read_text(encoding="utf-8") if frag.exists() else None
    if args.check:
        if have != want:
            print(f"gen_topic_index: {frag.name} is stale; run python3 tools/gen_topic_index.py", file=sys.stderr)
            return 1
        print("gen_topic_index: 1 generated file(s) are current", file=sys.stderr)
        return 0
    if have != want:
        frag.parent.mkdir(parents=True, exist_ok=True)
        frag.write_text(want, encoding="utf-8")
    print(f"gen_topic_index: wrote {frag}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
